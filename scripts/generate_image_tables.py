#!/usr/bin/env python3
"""Generate the integer transfer-curve tables in stdlib/std/image/color.dodo.

The sRGB curve (IEC 61966-2-1) is evaluated with exact rationals where it is
linear and with Python floats (binary64) for the power segment, then rounded
to the nearest 16-bit code. Run with --write to update the file in place or
--check to verify it; with neither, print the generated block.
"""

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "stdlib/std/image/color.dodo"
BEGIN = "// BEGIN GENERATED IMAGE TABLES"
END = "// END GENERATED IMAGE TABLES"


def srgb_to_linear(v: float) -> float:
    if v <= 0.04045:
        return v / 12.92
    return ((v + 0.055) / 1.055) ** 2.4


def linear_to_srgb(v: float) -> float:
    if v <= 0.0031308:
        return v * 12.92
    return 1.055 * v ** (1 / 2.4) - 0.055


def code(value: float) -> int:
    return max(0, min(65535, int(value * 65535 + 0.5)))


def table(name: str, values: list[int]) -> str:
    lines = [f"static {name}: [{len(values)}]u16 = ["]
    for start in range(0, len(values), 16):
        chunk = ", ".join(str(v) for v in values[start:start + 16])
        comma = "," if start + 16 < len(values) else ""
        lines.append(f"    {chunk}{comma}")
    lines.append("]")
    return "\n".join(lines)


def block() -> str:
    # Knots at every 8-bit code (v = i * 257), so 8-bit input is exact.
    to_linear = [code(srgb_to_linear(i / 255)) for i in range(256)]
    # Knots every 16 linear codes; the last knot is the curve at 1.0.
    to_srgb = [code(linear_to_srgb(min(j * 16, 65535) / 65535)) for j in range(4097)]
    return "\n".join([
        BEGIN,
        "// Generated by scripts/generate_image_tables.py.",
        table("SRGB_TO_LINEAR", to_linear),
        table("LINEAR_TO_SRGB", to_srgb),
        END,
    ])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = block()
    if not args.write and not args.check:
        print(generated)
        return 0
    text = TARGET.read_text()
    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    if args.check:
        if text[start:end] != generated:
            print(f"{TARGET} tables are stale; run {Path(__file__).name} --write", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text[:start] + generated + text[end:])
    return 0


if __name__ == "__main__":
    sys.exit(main())
