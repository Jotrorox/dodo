"""Generate the bitmap font tables in stdlib/std/graphics/font.dodo.

The glyphs below were drawn for Dodo and are dedicated to the public domain
along with the rest of this file's data. Both fonts cover U+0020 through
U+00FF (ASCII and Latin-1). Accented Latin-1 letters are composed from a base
letter and an accent; code points without a drawing (the C1 controls and a
few symbols) store the replacement box that std/graphics also draws for
characters outside a font.

SMALL is 6x8: glyphs are 5 columns wide plus one column of spacing, capitals
use rows 0-6 and descenders row 7. Accented capitals use 5-row capitals so
the accent fits in rows 0-1.

MEDIUM is 8x16: glyphs are 7 columns wide plus one of spacing. Rows 0-2 hold
accents over capitals, capitals use rows 3-12, lowercase x-height rows 6-12,
descenders rows 13-15. The art below starts at row 3.

Run with --check to verify the checked-in block, --write to regenerate it,
or --preview to print every glyph as text.
"""

