def parse(art: str, rows: int, width: int) -> dict[int, list[str]]:
    """Parse bands: a header naming each glyph, then `rows` lines of art."""
    glyphs: dict[int, list[str]] = {}
    lines = [line.rstrip() for line in art.strip("\n").split("\n")]
    index = 0
    while index < len(lines):
        if not lines[index].strip():
            index += 1
            continue
        names = lines[index].split()
        band = lines[index + 1 : index + 1 + rows]
        if len(band) != rows:
            raise ValueError(f"band {names} has {len(band)} rows, expected {rows}")
        cells = [line.split() for line in band]
        for row, cell in enumerate(cells):
            if len(cell) != len(names):
                raise ValueError(f"band {names} row {row} has {len(cell)} cells")
        for column, name in enumerate(names):
            code = name_to_code(name)
            if code in glyphs:
                raise ValueError(f"glyph {name} defined twice")
            glyph = [cells[row][column] for row in range(rows)]
            for row in glyph:
                if len(row) != width or set(row) - {".", "#"}:
                    raise ValueError(f"glyph {name} has malformed row {row!r}")
            glyphs[code] = glyph
        index += 1 + rows
    return glyphs


def name_to_code(name: str) -> int:
    if name == "SP":
        return 0x20
    if name.startswith("U+"):
        return int(name[2:], 16)
    if len(name) != 1:
        raise ValueError(f"bad glyph name {name!r}")
    return ord(name)


