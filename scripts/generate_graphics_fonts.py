def overlay(glyph: list[str], top: int, mark: list[str]) -> list[str]:
    result = list(glyph)
    for offset, row in enumerate(mark):
        merged = "".join("#" if a == "#" or b == "#" else "." for a, b in zip(result[top + offset], row))
        result[top + offset] = merged
    return result


def replacement_box(width: int, height: int) -> list[str]:
    """Matches the box std/graphics draws for characters outside a font."""
    inner = width - 1
    rows = []
    for row in range(height):
        if row >= height - 1:
            rows.append("." * width)
        elif row == 0 or row == height - 2:
            rows.append("#" * inner + ".")
        else:
            rows.append("#" + "." * (inner - 2) + "#" + ".")
    return rows


def small_font() -> dict[int, list[str]]:
    glyphs = {code: [row + "." for row in rows] for code, rows in parse(SMALL_ART, 8, 5).items()}
    short = parse(SMALL_SHORT_CAPS, 5, 5)
    for code, (base, accent) in COMPOSED.items():
        if accent == "cedilla":
            glyph = glyphs[ord(base)]
            bottom = glyph[7][:5]
            mark = "".join("#" if a == "#" or b == "#" else "." for a, b in zip(bottom, SMALL_CEDILLA))
            glyphs[code] = glyph[:7] + [mark + "."]
            continue
        if base.isupper():
            body = ["....."] * 2 + short[ord(base)] + ["....."]
        elif base == "i":
            body = SMALL_DOTLESS_I
        else:
            body = [row[:5] for row in glyphs[ord(base)]]
        glyphs[code] = [row + "." for row in overlay(body, 0, SMALL_ACCENTS[accent])]
    return glyphs


def medium_font() -> dict[int, list[str]]:
    glyphs = {code: ["......."] * 3 + rows for code, rows in parse(MEDIUM_ART, 13, 7).items()}
    for code, (base, accent) in COMPOSED.items():
        body = list(glyphs[ord(base)])
        if base == "i":
            # Dotless i: drop the dot at row 4.
            body[4] = "......."
        if accent == "cedilla":
            glyphs[code] = overlay(body, 13, MEDIUM_CEDILLA)
        elif base.isupper():
            glyphs[code] = overlay(body, 0, MEDIUM_ACCENTS[accent])
        else:
            glyphs[code] = overlay(body, 3, MEDIUM_ACCENTS[accent])
    return {code: [row + "." for row in rows] for code, rows in glyphs.items()}


def table(glyphs: dict[int, list[str]], width: int, height: int) -> list[int]:
    box = replacement_box(width, height)
    data = []
    for code in range(FIRST, LAST + 1):
        rows = glyphs.get(code, box)
        assert len(rows) == height and all(len(row) == width for row in rows), hex(code)
        for row in rows:
            value = 0
            for column, pixel in enumerate(row):
                if pixel == "#":
                    value |= 0x80 >> column
            data.append(value)
    return data


def dodo_array(name: str, data: list[int]) -> str:
    lines = [f"static {name}: [{len(data)}]u8 = ["]
    for start in range(0, len(data), 16):
        chunk = ", ".join(f"0x{value:02x}" for value in data[start : start + 16])
        lines.append(f"    {chunk},")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("]")
    return "\n".join(lines)


def generated_block() -> str:
    small = table(small_font(), 6, 8)
    medium = table(medium_font(), 8, 16)
    return "\n".join([
        BEGIN,
        "// Generated by scripts/generate_graphics_fonts.py; edit the art there.",
        dodo_array("SMALL_GLYPHS", small),
        dodo_array("MEDIUM_GLYPHS", medium),
        END,
    ])


def preview() -> None:
    for name, glyphs, width, height in (("SMALL", small_font(), 6, 8), ("MEDIUM", medium_font(), 8, 16)):
        box = replacement_box(width, height)
        print(f"== {name} ==")
        codes = list(range(FIRST, LAST + 1))
        for start in range(0, len(codes), 16):
            band = codes[start : start + 16]
            print("  ".join(f"{code:02X}".ljust(width) for code in band))
            for row in range(height):
                print("  ".join(glyphs.get(code, box)[row] for code in band))
            print()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if the generated block differs")
    mode.add_argument("--write", action="store_true", help="replace the generated block")
    mode.add_argument("--preview", action="store_true", help="print every glyph as text")
    args = parser.parse_args()
    if args.preview:
        preview()
        return 0
    block = generated_block()
    if not (args.check or args.write):
        print(block)
        return 0
    text = TARGET.read_text()
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0 or end < start:
        print(f"{TARGET}: missing {BEGIN} / {END} markers", file=sys.stderr)
        return 1
    updated = text[:start] + block + text[end + len(END) :]
    if args.check:
        if updated != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date; run {Path(__file__).name} --write", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(updated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
