#!/usr/bin/env python3
"""Regenerate the shader constants at the end of tests/stdlib/gpu_checks.dodo.

The readable sources live in tests/gpu/shaders: one Metal Shading Language
file with every function the checks use, and one GLSL 4.50 file per
pipeline. OpenGL compiles the GLSL as is (std/gpu inserts `#define VERTEX`,
`FRAGMENT` or `COMPUTE`); Vulkan takes SPIR-V compiled from the same files
with glslangValidator, which must be on PATH, with each entry point renamed
to the Metal function's name so that one name works for both.

Run with --write to update the fixture or --check to verify it.
"""

import argparse
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHADERS = ROOT / "tests/gpu/shaders"
FIXTURE = ROOT / "tests/stdlib/gpu_checks.dodo"
MARKER = "// Shaders, generated by scripts/generate_gpu_test_shaders.py from tests/gpu/shaders."

GLSL = [("update", "UPDATE"), ("double", "DOUBLE"), ("fill", "FILL"),
        ("color", "COLOR"), ("texture", "TEXTURE"), ("constant", "CONSTANT")]

# (constant, GLSL file, stage, entry point)
SPIRV = [
    ("UPDATE_SPIRV", "update", "comp", "update"),
    ("DOUBLE_SPIRV", "double", "comp", "double_values"),
    ("FILL_SPIRV", "fill", "comp", "fill"),
    ("COLOR_VERTEX_SPIRV", "color", "vert", "color_vertex"),
    ("COLOR_FRAGMENT_SPIRV", "color", "frag", "color_fragment"),
    ("SCREEN_VERTEX_SPIRV", "texture", "vert", "screen_vertex"),
    ("TEXTURE_FRAGMENT_SPIRV", "texture", "frag", "texture_fragment"),
    ("CONSTANT_FRAGMENT_SPIRV", "constant", "frag", "constant_fragment"),
]

DEFINES = {"comp": "COMPUTE", "vert": "VERTEX", "frag": "FRAGMENT"}


def string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def compile_spirv(name: str, stage: str, entry: str) -> list[int]:
    with tempfile.TemporaryDirectory() as directory:
        output = Path(directory) / "shader.spv"
        subprocess.run(
            ["glslangValidator", "-V", "--target-env", "vulkan1.2", "-S", stage,
             f"-D{DEFINES[stage]}", "-e", entry, "--source-entrypoint", "main",
             "-o", str(output), str(SHADERS / f"{name}.glsl")],
            check=True, stdout=subprocess.DEVNULL)
        data = output.read_bytes()
    return list(struct.unpack(f"<{len(data) // 4}I", data))


def words_constant(name: str, words: list[int]) -> str:
    rows = ["    " + ", ".join(f"0x{word:08x}" for word in words[i:i + 6]) + ","
            for i in range(0, len(words), 6)]
    return f"const {name}: [{len(words)}]u32 = [\n" + "\n".join(rows) + "\n]\n"


def generate() -> str:
    parts = [MARKER + "\n"]
    parts.append("const MSL: &str = " + string((SHADERS / "shaders.metal").read_text()) + "\n")
    for name, constant in GLSL:
        parts.append(f"const {constant}_GLSL: &str = " + string((SHADERS / f"{name}.glsl").read_text()) + "\n")
    for constant, name, stage, entry in SPIRV:
        parts.append(words_constant(constant, compile_spirv(name, stage, entry)))
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    current = FIXTURE.read_text()
    head, separator, _ = current.partition(MARKER)
    if not separator:
        print(f"{FIXTURE}: missing the line '{MARKER}'", file=sys.stderr)
        return 1
    updated = head + generate()
    if arguments.check:
        if updated != current:
            print(f"{FIXTURE} is stale; run scripts/generate_gpu_test_shaders.py --write", file=sys.stderr)
            return 1
        return 0
    FIXTURE.write_text(updated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
