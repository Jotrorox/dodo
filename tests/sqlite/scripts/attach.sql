-- ATTACH / DETACH: schema-qualified names, lookup order, transactions over
-- several database files, errors.
create table t(id integer primary key, v text);
insert into t values (1, 'main-1'), (2, 'main-2');
attach database 'aux1.db' as aux;
attach 'aux2.db' as "Second";
pragma database_list;
create table aux.t(id integer primary key, v text, n int);
create table aux.only_aux(x);
create table second.s(k text primary key, w) without rowid;
insert into aux.t values (1, 'aux-1', 10), (5, 'aux-5', 50);
insert into aux.only_aux values ('alone');
insert into second.s values ('b', 2), ('a', 1);
-- Unqualified names: main before attached databases.
select * from t order by id;
select * from aux.t order by id;
select * from main.t order by id;
select * from only_aux;
select * from second.s;
select * from SECOND.S where k = 'a';
-- Columns qualified with schema and table.
select aux.t.v, main.t.v from aux.t, main.t where aux.t.id = main.t.id;
select x.v, y.v from main.t as x join aux.t as y on x.id = y.id;
select main.t.id, aux.t.n from main.t left join aux.t on main.t.id = aux.t.id order by 1;
select count(*) from t, aux.t, second.s;
select (select v from aux.t where id = t.id) from t order by id;
select id from t where id in (select id from aux.t);
select id from aux.t where exists (select 1 from main.t where main.t.id = aux.t.id);
-- Writes across databases.
insert into aux.t(id, v, n) select id + 100, v || '!', id from main.t;
update aux.t set n = n + 1 where id > 100;
delete from aux.t where id = 102;
select * from aux.t order by id;
insert into t(v) select v from aux.t where id = 5;
select * from t order by id;
update second.s set w = w * 10;
delete from second.s where k = 'b';
select * from second.s;
-- The catalog of each database.
select type, name, tbl_name, sql from aux.sqlite_master order by name;
select type, name, tbl_name, sql from second.sqlite_schema order by name;
select type, name from main.sqlite_master order by name;
select name from sqlite_master order by name;
-- Indexes go into their table's database.
create index aux.t_v on t(v);
create index t_n on only_aux(x);
create unique index second.s_w on s(w);
select type, name, tbl_name from aux.sqlite_master order by name;
select type, name, tbl_name from second.sqlite_master order by name;
select type, name from main.sqlite_master order by name;
select v from aux.t where v = 'aux-5';
select * from aux.t indexed by t_v where v > 'aux';
pragma aux.index_list(t);
pragma aux.table_info(t);
pragma table_info(only_aux);
pragma second.index_info(s_w);
-- Header fields are per database.
pragma aux.user_version = 7;
pragma user_version;
pragma aux.user_version;
pragma second.user_version;
pragma main.user_version = 3;
pragma user_version;
pragma aux.application_id = 99;
pragma aux.application_id;
pragma aux.page_size;
pragma aux.encoding;
pragma aux.schema_version;
pragma aux.journal_mode;
pragma aux.integrity_check;
pragma integrity_check;
pragma second.freelist_count;
-- Transactions over several files.
begin;
insert into t values (50, 'txn');
insert into aux.t values (50, 'txn', 0);
insert into second.s values ('z', 26);
commit;
select count(*) from t where id = 50;
select count(*) from aux.t where id = 50;
select * from second.s where k = 'z';
begin;
delete from t;
delete from aux.t;
delete from second.s;
select count(*) from t;
rollback;
select count(*) from t;
select count(*) from aux.t;
select count(*) from second.s;
-- A failing statement inside a transaction undoes its own changes only.
begin;
insert into aux.t values (60, 'kept', 0);
insert into t select id + 1000, v from aux.t;
insert into aux.t select id, v, n from aux.t;
select count(*) from aux.t where id = 60;
select count(*) from t where id > 1000;
commit;
select count(*) from aux.t;
select count(*) from t;
-- Savepoints span databases.
savepoint a;
insert into aux.t values (70, 'sp', 0);
savepoint b;
insert into t values (70, 'sp');
delete from second.s;
rollback to b;
select count(*) from t where id = 70;
select count(*) from second.s;
release a;
select count(*) from aux.t where id = 70;
-- Autoincrement keeps its sequence in the table's database.
create table aux.ai(id integer primary key autoincrement, x);
insert into aux.ai(x) values ('a'), ('b');
delete from aux.ai;
insert into aux.ai(x) values ('c');
select * from aux.ai;
select * from aux.sqlite_sequence;
select name from main.sqlite_master where name = 'sqlite_sequence';
-- Views and triggers inside an attached database refer to its own tables.
create view aux.v as select id, v from t where id < 100;
select * from aux.v order by id;
select * from v order by id;
create table aux.log(msg);
create trigger aux.t_ins after insert on t begin insert into log values ('aux.t got ' || new.id); end;
insert into aux.t values (80, 'trig', 0);
insert into main.t values (81, 'not logged');
select * from aux.log;
select type, name, tbl_name, sql from aux.sqlite_master where type in ('view', 'trigger') order by name;
-- ALTER and DROP in an attached database.
alter table aux.only_aux add column y default 5;
select * from aux.only_aux;
alter table aux.only_aux rename to renamed;
select type, name, tbl_name, sql from aux.sqlite_master where tbl_name = 'renamed' order by name;
alter table aux.renamed rename column x to xx;
select xx, y from renamed;
drop index aux.t_v;
drop table aux.renamed;
drop view aux.v;
drop trigger aux.t_ins;
select type, name from aux.sqlite_master order by name;
-- Errors.
attach 'aux1.db' as aux;
