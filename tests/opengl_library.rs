//! OpenGL contexts: code generation for every hosted target, adapter
//! selection, the generated binding's shape, and a triangle rendered and
//! read back wherever the machine has OpenGL 3.3 (Mesa's llvmpipe in Linux
//! CI, CGL on macOS).
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

fn success(output: &Output, context: &str) {
    assert!(
        output.status.success(),
        "{context}: {}\n{}\n{}",
        output.status,
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

struct Scratch(PathBuf);
impl Scratch {
    fn new(name: &str) -> Self {
        let path = std::env::temp_dir().join(format!("dodo-opengl-{name}-{}", std::process::id()));
        fs::create_dir_all(&path).unwrap();
        Self(path)
    }
}
impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn dodo(args: &[&str], extra: &Path) -> Output {
    Command::new(env!("CARGO_BIN_EXE_dodo"))
        .args(args)
        .arg(extra)
        .output()
        .unwrap()
}

#[test]
fn opengl_builds_for_every_hosted_target() {
    let scratch = Scratch::new("targets");
    for source in [
        "tests/gpu/opengl_checks.dodo",
        "examples/opengl_window.dodo",
    ] {
        let source = root().join(source);
        for target in [
            "x86_64-unknown-linux-gnu",
            "aarch64-unknown-linux-gnu",
            "aarch64-apple-darwin",
            "x86_64-apple-darwin",
            "x86_64-pc-windows-msvc",
            "x86_64-pc-windows-gnu",
        ] {
            let object = scratch.0.join(format!("opengl-{target}.o"));
            success(
                &dodo(
                    &[
                        "build",
                        source.to_str().unwrap(),
                        "--emit",
                        "obj",
                        "--target",
                        target,
                        "-o",
                    ],
                    &object,
                ),
                &format!("emit {} for {target}", source.display()),
            );
            assert!(fs::metadata(object).unwrap().len() > 0);
        }
    }
    // The raw binding needs no operating system: it only calls through
    // addresses that someone loaded.
    let portable = scratch.0.join("portable.dodo");
    fs::write(
        &portable,
        "package main\nimport \"std/gpu/opengl/gl\"\nfn main() {\n    core.assert(!gl.is_loaded(\"glClear\"))\n    core.assert_eq(gl.COLOR_BUFFER_BIT, 0x4000u32)\n}\n",
    )
    .unwrap();
    for target in ["wasm32-unknown-unknown", "thumbv6m-none-eabi"] {
        let object = scratch.0.join(format!("portable-{target}.o"));
        success(
            &dodo(
                &[
                    "build",
                    portable.to_str().unwrap(),
                    "--emit",
                    "obj",
                    "--target",
                    target,
                    "-o",
                ],
                &object,
            ),
            &format!("emit std/gpu/opengl/gl for {target}"),
        );
    }
    // One adapter per OS, as for std/window; none for other targets.
    for (import, target, expected) in [
        (
            "std/gpu/opengl/posix",
            "x86_64-unknown-linux-gnu",
            "cannot be used",
        ),
        (
            "std/gpu/opengl/macos",
            "x86_64-unknown-linux-gnu",
            "cannot be used",
        ),
        (
            "std/gpu/opengl/linux",
            "x86_64-pc-windows-msvc",
            "cannot be used",
        ),
        ("std/gpu/opengl", "wasm32-unknown-unknown", "unsupported"),
    ] {
        let program = scratch.0.join("adapter.dodo");
        fs::write(
            &program,
            format!("package main\nimport \"{import}\"\nfn main() {{}}\n"),
        )
        .unwrap();
        let output = dodo(&["check", "--target", target], &program);
        assert!(!output.status.success(), "{import} accepted for {target}");
        let stderr = String::from_utf8_lossy(&output.stderr);
        assert!(stderr.contains(expected), "{import} for {target}: {stderr}");
    }
}

/// The checked-in binding matches the shape the generator writes: one name,
/// one table slot and one wrapper per command, and no hand edits to the
/// header. scripts/generate_opengl.py --check compares it with the registry.
#[test]
fn generated_binding_is_consistent() {
    let text = fs::read_to_string(root().join("stdlib/std/gpu/opengl/gl.dodo")).unwrap();
    assert!(text.starts_with(
        "package gl\n\n// GENERATED by scripts/generate_opengl.py from the Khronos OpenGL registry"
    ));
    let count: usize = text
        .lines()
        .find_map(|line| line.strip_prefix("pub const COMMAND_COUNT: usize = "))
        .unwrap()
        .parse()
        .unwrap();
    let names = text
        .lines()
        .find_map(|line| line.strip_prefix("const NAMES: &[u8] = b\""))
        .unwrap();
    assert_eq!(names.matches("\\0").count(), count);
    let wrappers: Vec<&str> = text
        .lines()
        .filter(|line| {
            line.starts_with("pub unsafe fn ")
                && !line.contains("fn load(")
                && !line.contains("fn unload(")
        })
        .collect();
    assert_eq!(wrappers.len(), count);
    for (index, name) in names.split("\\0").take(count).enumerate() {
        assert!(
            text.contains(&format!("        address := ADDRESSES[{index}]\n        core.assert(address != 0) // {name} is not loaded\n")),
            "slot {index} is not {name}"
        );
    }
    for expected in [
        "pub unsafe fn clear_color(red: f32, green: f32, blue: f32, alpha: f32) {",
        "pub unsafe fn tex_image_2d(",
        "pub unsafe fn shader_source(shader: u32, count: i32, string: *const *const u8, length: *const i32) {",
        "pub unsafe fn get_string(name: u32) -> *const u8 {",
        "pub unsafe fn uniform_matrix_4x3fv(",
        "pub unsafe fn vertex_attrib_i4ui(",
        "pub unsafe fn dispatch_compute(",
        "pub unsafe fn specialize_shader(",
        "pub const COLOR_BUFFER_BIT: u32 = 0x00004000",
        "pub const TIMEOUT_IGNORED: u64 = 0xffffffffffffffff",
    ] {
        assert!(text.contains(expected), "missing {expected:?}");
    }
    // The core profile drops the fixed-function pipeline.
    for removed in [
        "pub unsafe fn begin(",
        "pub unsafe fn matrix_mode(",
        "pub const QUADS:",
    ] {
        assert!(!text.contains(removed), "core profile contains {removed:?}");
    }
}

#[test]
fn triangle_renders_and_reads_back() {
    let required = std::env::var_os("DODO_REQUIRE_OPENGL_TESTS").is_some();
    let scratch = Scratch::new("triangle");
    for optimization in ["0", "2"] {
        let executable = scratch.0.join(format!(
            "checks-O{optimization}{}",
            std::env::consts::EXE_SUFFIX
        ));
        let source = root().join("tests/gpu/opengl_checks.dodo");
        success(
            &dodo(
                &["build", source.to_str().unwrap(), "-O", optimization, "-o"],
                &executable,
            ),
            &format!("compile the OpenGL checks -O{optimization}"),
        );
        let output = Command::new(&executable).output().unwrap();
        success(
            &output,
            &format!("execute the OpenGL checks -O{optimization}"),
        );
        let stdout = String::from_utf8_lossy(&output.stdout);
        if let Some(reason) = stdout.strip_prefix("unavailable\n") {
            assert!(!required, "OpenGL is required but unavailable: {reason}");
            eprintln!("skipping: no OpenGL 3.3 ({})", reason.trim());
            return;
        }
        assert!(stdout.ends_with("passed\n"), "{stdout}");
    }
}
