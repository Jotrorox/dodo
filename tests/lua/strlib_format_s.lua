-- string.format: %s with width/precision, __tostring, argument errors
local function esc(s) return (s:gsub("%z", "\\0")) end
local function f(fmt, ...)
  local ok, r = pcall(string.format, fmt, ...)
  if ok then print(string.format("%-10s", fmt), "[" .. esc(r) .. "]")
  else print(string.format("%-10s", fmt), "error: " .. r) end
end

f("%s", "hello")
f("%10s|", "hello")
f("%-10s|", "hello")
f("%.2s", "hello")
f("%5.2s|", "hello")
f("%-5.2s|", "hello")
f("%.0s|", "hello")
f("%.10s", "hello")
f("%s", "")
f("%5s|", "")
f("%s", 42)
f("%s", 4.0)
f("%s", -0.0)
f("%s", math.mininteger)
f("%5s|", 1.5)
f("%.1s", 123)
f("%s", nil)
f("%s", true)
f("%s %s", false, nil)
f("%s", "a\0b")
f("%.5s", "a\0b")
f("%5s", "a\0b")
f("%s", ("x"):rep(120))
f("%-3s|", ("y"):rep(105))
f("%99s|", "z")
f("%s")
f("%s%s", 1)
f("%s|%d|%s", "a", 2, "c")
f("no conversions", 1, 2, 3)
f("")

-- __tostring and __name
local obj = setmetatable({}, {__tostring = function() return "OBJ" end})
f("%s", obj)
f("%5s|", obj)
f("%.1s", obj)
local bad = setmetatable({}, {__tostring = function() return 42 end})
f("%s", bad)
local bad2 = setmetatable({}, {__tostring = function() return nil end})
f("%s", bad2)
local named = setmetatable({}, {__name = "MyType", __tostring = function(t) return "named!" end})
f("%s", named)
local errs = setmetatable({}, {__tostring = function() error("boom") end})
f("%s", errs)
print(tostring(obj), tostring(named))
local onlyname = setmetatable({}, {__name = "OnlyName"})
print((tostring(onlyname):gsub("0x%x+", "ADDR"):gsub(": [%x]+$", ": ADDR")))
print(type(tostring({})), tostring({}):match("^table: ") ~= nil)

-- format string and argument errors
print(pcall(string.format))
print(pcall(string.format, nil))
print(pcall(string.format, {}))
print(pcall(string.format, 12, 3))
f(5)
f("%d", "x")
f("%x", 1.5)
f("%c")
f("%s %s %s", 1, 2)
print(select("#", string.format("%s", 1)))
-- the format string itself may contain zeros
print(esc(string.format("a\0%d\0b", 7)), #string.format("\0\0"))
