-- Lexer: error messages reported by load() for malformed tokens
local function esc(s)
  return (s:gsub("[%c]", function(c) return string.format("\\%d", c:byte()) end))
end
local function try(src)
  local f, err = load(src, "=src")
  if f then
    print(esc(src), "=> loaded")
  else
    print(esc(src), "=> " .. esc(err))
  end
end

