-- string.format: floating-point conversions (%f %e %E %g %G %a %A) with flags
local function f(fmt, ...)
  local ok, r = pcall(string.format, fmt, ...)
  if ok then print(string.format("%-10s", fmt), "[" .. r .. "]")
  else print(string.format("%-10s", fmt), "error: " .. r) end
end
local inf = math.huge

for _, v in ipairs{0.0, 1, -1.5, 0.1, 1 / 3, 1e300, 1e-300, math.pi, 2^63, 123456789.125} do
  print("value", v)
  f("%f", v); f("%e", v); f("%E", v); f("%g", v); f("%G", v)
end
f("%f", -0.0)
f("%e", -0.0)
f("%g", -0.0)
f("%f", inf)
f("%f", -inf)
f("%e", inf)
f("%g", -inf)
f("%E", inf)
f("%G", -inf)
f("%5.1f", inf)
f("%-6f|", -inf)
f("%+f", inf)
f("%f", 3)
f("%f", "2.5")
f("%f", "0x10")
f("%f", "x")
f("%f", {})

-- precision, width and flags
f("%.3f", math.pi)
f("%10.3f", math.pi)
f("%-10.3f|", math.pi)
f("%010.3f", -math.pi)
f("%+.2e", 12345.678)
f("% .2e", 12345.678)
f("%.0f", 0.5)
f("%.0f", 1.5)
f("%.0f", 2.5)
f("%.0f", -0.5)
f("%#.0f", 3)
f("%.0e", 12345)
f("%#.0e", 12345)
f("%.20f", 0.1)
f("%.17g", 0.1)
f("%.15g", 0.1)
f("%#g", 1)
f("%#g", 0.5)
f("%g", 100000)
f("%g", 1000000)
f("%g", 1e-4)
f("%g", 1e-5)
f("%g", 123456789)
f("%.3g", 0.0001234)
f("%.0g", 15)
f("%.1g", 0.05)
f("%10.4g|", 1 / 3)
f("%-10.2G|", 1e-10)
f("%099.10f", 1)
f("%.99f", 1 / 3)
f("%5.3s|", "abcdef")
f("%.14g", 2^63)
f("%.14g", 0.1 + 0.2)
f("%.16g", 0.1 + 0.2)
f("%f", 1e15)
f("%.2f", 2^53 + 1)
f("%e", 5e-324)
f("%g", 2^-1022)

-- hexadecimal floats
for _, v in ipairs{1.0, 0.5, 0.1, -2.75, 1024, 2^-1022, 1e300, 3, 0.0, -0.0, math.pi} do
  f("%a", v); f("%A", v)
end
f("%a", inf)
f("%A", -inf)
f("%.3a", 1.0)
f("%20a|", 1.0)
f("%-20a|", 1.0)
f("%+a", 1.0)
f("%#a", 1.0)
f("%020a", 1.0)

-- invalid flag combinations
f("%#5.2q", 1)
f("%Lf", 1)
f("%.f", 1.5)
f("%5.f|", 1.5)
f("%e", nil)
