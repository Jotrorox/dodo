-- Patterns: string.find / string.match with init, plain flag, anchors, quantifiers
local function show(label, ...)
  local t = table.pack(...)
  for i = 1, t.n do t[i] = tostring(t[i]) end
  print(label, t.n, table.concat(t, " "))
end
local s = "hello world"

show("find basic", s:find("o"))
show("find word", s:find("world"))
show("find none", s:find("xyz"))
show("find init 6", s:find("o", 6))
show("find init -5", s:find("o", -5))
show("find init 0", s:find("h", 0))
show("find init -100", s:find("h", -100))
show("find init #s", s:find("d", #s))
show("find init #s+1 empty", s:find("", #s + 1))
show("find init #s+2 empty", s:find("", #s + 2))
show("find init #s+1 x", s:find("x*", #s + 1))
show("find empty", s:find(""))
show("find empty init 5", s:find("", 5))
show("find captures", s:find("(h)(e)(l+)"))
show("find position capture", s:find("()o()"))
show("find anchored", s:find("^hello"))
show("find anchored fail", s:find("^world"))
show("find anchored init", s:find("^world", 7))
show("find end anchor", s:find("world$"))
show("find end anchor fail", s:find("hello$"))
show("find ^$ empty", (""):find("^$"))
show("find number subject", string.find(12345, "3"))
show("find number pattern", ("a1b2"):find(2))

-- plain finds ignore magic characters
show("plain dot", ("a.b"):find(".", 1, true))
show("pattern dot", ("a.b"):find("."))
show("plain magic", ("x(%a+)*?[]^$y"):find("(%a+)*?[]^$", 1, true))
show("plain with init", ("a+b+c"):find("+", 3, true))
show("plain empty", ("abc"):find("", 2, true))
show("plain empty past end", ("abc"):find("", 10, true))
show("plain not found", ("abc"):find("d", 1, true))
show("plain false flag", ("a.b"):find(".", 1, false))
show("plain nil init", ("a.b"):find("b", nil, true))

-- match
show("match whole", s:match("o w"))
show("match capture", s:match("(%w+) (%w+)"))
show("match none", s:match("%d+"))
show("match init", s:match("%w+", 7))
show("match init neg", s:match("%w+", -3))
show("match position", s:match("()ll()"))
show("match empty capture", s:match("()"))
show("match anchored init", s:match("^o", 5))
show("match past end", s:match(".*", 100))

-- special characters as literals
show("caret mid", ("a^b"):find("a^b"))
show("dollar mid", ("a$b"):find("a$b"))
show("escaped dollar end", ("cost$"):find("%$$"))
show("escaped dot", ("a.b"):find("%."))
show("escaped percent", ("50%"):match("%d+%%"))
show("escaped dash", ("a-b"):match("a%-b"))
show("escaped brackets", ("[x]"):match("%[(.)%]"))
show("escaped parens", ("f(x)"):match("%((.-)%)"))
show("non-alnum escape", ("a@b"):match("%@"))

-- quantifiers
show("star greedy", ("<a><b>"):match("<.*>"))
show("lazy", ("<a><b>"):match("<.->"))
show("plus", ("aaab"):match("a+"))
show("plus fail", ("bbb"):match("a+"))
show("optional present", ("ab"):match("a?b"))
show("optional absent", ("b"):match("a?b"))
show("lazy anchored", ("aaa"):match("^a-$"))
show("lazy empty", ("aaa"):match("a-"))
show("star empty", ("bbb"):match("a*"))
show("star backtrack", ("aaab"):match("a*ab"))
show("plus backtrack", ("xaaay"):match("x(a+)a"))
show("lazy then fixed", ("key=val;k2=v2"):match("(.-)=(.-);"))
show("quantifier on class", ("  42  "):match("%s*(%d+)%s*$"))
show("question then end", ("color"):match("colou?r"), ("colour"):match("colou?r"))
show("star on set", ("aabbccd"):match("[abc]*"))
show("dot matches zero", ("a\0b"):match("a.b") == "a\0b")
show("literal star first", ("*x"):find("*"))
show("literal plus first", ("+x"):find("+"))
