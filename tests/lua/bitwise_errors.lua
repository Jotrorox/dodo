-- Bitwise: error messages for non-integral and non-numeric operands
local function try(label, f)
  local ok, v = pcall(f)
  if ok then print(label, "ok", math.type(v), v)
  else print(label, "err", v) end
end
local x, s, t, b = 1.5, "abc", {}, true
try("1.5 & 1 (const)", load("return 1.5 & 1", "=c"))
try("upvalue 1.5 & 1", function() return x & 1 end)
try("1 | upvalue 1.5", function() return 1 | x end)
try("~1.5", function() return ~x end)
try("1 << 1.5", function() return 1 << x end)
try("2^63 | 0", function() return 2^63 | 0 end)
try("huge ~ 0", function() return math.huge ~ 0 end)
try("nan & 0", function() return (0 / 0) & 0 end)
try("'1.5' | 0", function() return "1.5" | 0 end)
try("'abc' | 0", function() return "abc" | 0 end)
try("upvalue s & 1", function() return s & 1 end)
try("1 ~ upvalue s", function() return 1 ~ s end)
try("~upvalue s", function() return ~s end)
try("'9223372036854775808' | 0", function() return "9223372036854775808" | 0 end)
try("'1e100' | 0", function() return "1e100" | 0 end)
try("table & 1", function() return t & 1 end)
try("1 & table", function() return 1 & t end)
try("bool | 1", function() return b | 1 end)
try("nil >> 1", function() return t.none >> 1 end)
try("global nil << 1", function() return undefinedvar << 1 end)
try("~table", function() return ~t end)
try("~nil", function() return ~nil end)
try("function & 1", function() return print & 1 end)
try("1.5 & table", function() return x & t end)
try("table & 1.5", function() return t & x end)
try("'abc' & 1.5", function() return s & x end)
try("upvalue float", function() local f = function() return x | 0 end; return f() end)
try("field float", function() local r = {v = 2.5}; return r.v | 0 end)
try("true local", function() local y = 0.5; return y | 0 end)
try("local string", function() local y = "7"; return y >> 0 end)
try("call result float", function() return math.sqrt(2) | 0 end)
-- errors from constant folding are deferred to run time
local f, err = load("return 1 // 0, 1.5 | 0")
print("load of constant bad expr", type(f), err)
