-- tonumber with an explicit base (2..36): digits, case, signs, whitespace, wraparound
local function esc(s) return (s:gsub("[^\32-\126]", function(c) return string.format("\\%d", c:byte()) end)) end
local function t(s, base)
  local ok, r = pcall(tonumber, s, base)
  local label = (type(s) == "string" and '"' .. esc(s) .. '"' or
                 type(s) == "table" and "table" or tostring(s)) .. " base " .. tostring(base)
  if not ok then print(label, "error: " .. r)
  elseif r == nil then print(label, "nil")
  else print(label, math.type(r), r) end
end

