-- string.format: integer and character conversions (%d %i %x %X %o %c) with flags
local function esc(s) return (s:gsub("[^\32-\126]", function(c) return string.format("\\x%02X", c:byte()) end)) end
local function f(fmt, ...)
  local ok, r = pcall(string.format, fmt, ...)
  if ok then print(string.format("%-12s", fmt), "[" .. esc(r) .. "]")
  else print(string.format("%-12s", fmt), "error: " .. r) end
end
local maxi, mini = math.maxinteger, math.mininteger

for _, v in ipairs{0, 1, -1, 42, -42, maxi, mini} do
  f("%d", v)
end
f("%i", 123)
f("%5d", 42)
f("%-5d|", 42)
f("%05d", 42)
f("%05d", -42)
f("%+d", 42)
f("%+d", -42)
f("% d", 42)
f("% d", -42)
f("%.3d", 7)
f("%.0d", 0)
f("%8.3d", 7)
f("%-8.3d|", -7)
f("%+05d", 3)
f("%99d", 1)
f("%d", 3.0)
f("%d", -0.0)
f("%d", 2^53)
f("%d", "10")
f("%d", "0x10")
f("%d", " 12 ")
f("%d", "3.0")
f("%d", 3.5)
f("%d", 2^63)
f("%d", "3.5")
f("%d", "abc")
f("%d", {})
f("%d", nil)
f("%d")
f("%d %d", 1)

-- hex and octal (negative numbers are shown as unsigned 64-bit)
for _, v in ipairs{0, 255, -1, maxi, mini, 4096} do
  f("%x", v); f("%X", v); f("%o", v)
end
f("%#x", 255)
f("%#X", 255)
f("%#o", 8)
f("%#x", 0)
f("%08x", 0xbeef)
f("%-8x|", 0xbeef)
f("%.6x", 0xab)
f("%#10.4x", 0xab)
f("%x", 15.0)
f("%x", 1.5)

-- characters
f("%c", 65)
f("%c%c%c", 76, 117, 97)
f("%c", 0)
f("%c", 255)
f("%5c|", 120)
f("%-5c|", 120)
f("%c", 65.0)
f("%c", "66")
f("%c", 65.5)

