-- Patterns: malformed pattern errors and matcher limits
local function try(label, f, ...)
  local ok, err = pcall(f, ...)
  print(label, ok, err)
end
local find, match, gsub = string.find, string.match, string.gsub

try("ends with %", find, "abc", "%")
try("ends with % after text", find, "abc", "ab%")
try("missing ]", find, "abc", "[a")
try("missing ] after ^", find, "abc", "[^")
try("missing ] escaped", find, "abc", "[a%]")
try("missing ] percent end", find, "abc", "[a%")
try("unfinished capture", find, "abc", "(a")
try("unfinished nested", find, "abc", "((a)")
try("invalid pattern capture", match, "abc", "a)")
try("invalid pattern capture gsub", gsub, "abc", "b)", "")
-- string.find with no special characters (")" is not one) does a plain search
try("find a) is a plain search", find, "xa)", "a)")
try("invalid capture index %1", find, "abc", "%1")
try("invalid capture index %2", find, "abc", "(a)%2")
try("unclosed capture ref", find, "abc", "(a%1)")
try("capture index %0", find, "abc", "(a)%0")
try("%f without [", find, "abc", "%fa")
try("%f at end", find, "abc", "%f")
try("%f missing ]", find, "abc", "%f[a")
try("%b no args", find, "abc", "%b")
try("%b one arg", find, "abc", "%ba")
try("too many captures", find, ("a"):rep(40), ("(a)"):rep(33))
try("32 captures ok", function() return select("#", find(("a"):rep(40), ("(a)"):rep(32))) end)
try("pattern too complex", find, ("a"):rep(300), ("a?"):rep(300) .. "b")
try("deep but ok", find, ("a"):rep(150), ("a?"):rep(150) .. "$")
try("match ends with %", match, "abc", "a%")
try("gsub ends with %", gsub, "abc", "%", "x")
try("gsub missing ]", gsub, "abc", "[", "x")
try("gmatch error on use", function() for _ in ("abc"):gmatch("[a") do end end)
-- errors only surface if the matcher reaches the bad part
try("lazy bad part not reached", find, "abc", "x[")
try("bad part reached", find, "xabc", "x[")
try("bad capture ref not reached", find, "abc", "z%1")
try("unfinished capture no match", find, "abc", "z(")
try("unfinished capture match", find, "abc", "a(")
-- special characters that are fine
try("lone ]", find, "a]", "]")
try("lone )", find, "a)", "%)")
try("lone ^ in set end", find, "a^", "[a^]+")
try("dash at end", find, "a-", "a-")
try("question alone", find, "?", "?")
try("percent letter-less", find, "%", "%%")
-- replacement-string errors
try("repl invalid %", gsub, "abc", "b", "%x")
try("repl capture too big", gsub, "abc", "(b)", "%3")
try("repl %1 no captures", gsub, "abc", "b", "[%1]")
try("repl %0", gsub, "abc", "b", "[%0]")
try("repl unfinished capture idx", gsub, "abc", "(b", "%1")
try("repl table value", gsub, "abc", "b", {b = {}})
try("repl function value", gsub, "abc", "b", function() return print end)
