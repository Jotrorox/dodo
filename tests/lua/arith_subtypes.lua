-- Arithmetic: integer/float subtypes of results and integer wraparound
local maxi, mini = math.maxinteger, math.mininteger
local function show(label, v) print(label, math.type(v), v) end

show("1", 1)
show("1.0", 1.0)
show("1+1", 1 + 1)
show("1+1.0", 1 + 1.0)
show("3*2", 3 * 2)
show("3*2.0", 3 * 2.0)
show("4/2", 4 / 2)
show("3/2", 3 / 2)
show("7//2", 7 // 2)
show("7.0//2", 7.0 // 2)
show("7//2.0", 7 // 2.0)
show("7%3", 7 % 3)
show("7.0%3", 7.0 % 3)
show("2^2", 2 ^ 2)
show("2^0.5", 2 ^ 0.5)
show("2^-1", 2 ^ -1)
show("(-8)^(1/3) is nan", (-8) ^ (1 / 3) ~= (-8) ^ (1 / 3))
show("-0", -0)
show("-0.0", -0.0)
show("0.0*-1", 0.0 * -1)
show("1-1.0", 1 - 1.0)
print("math.type of non-numbers", math.type("1"), math.type(nil), math.type({}))
print(pcall(math.type))

-- wraparound
show("maxint+1", maxi + 1)
show("minint-1", mini - 1)
show("maxint*2", maxi * 2)
show("minint*-1", mini * -1)
show("-minint", -mini)
show("minint//-1", mini // -1)
show("minint%-1", mini % -1)
show("maxint+maxint", maxi + maxi)
show("minint+minint", mini + mini)
show("maxint*maxint", maxi * maxi)
show("abs(minint)", math.abs(mini))
show("maxint+1.0", maxi + 1.0)
show("maxint+0.0 == 2^63", (maxi + 0.0 == 2 ^ 63) and 1 or 0)
show("minint+0.0", mini + 0.0)
print("wrap equalities", maxi + 1 == mini, mini - 1 == maxi, -mini == mini)
print("ult", math.ult(1, -1), math.ult(-1, 1), math.ult(maxi, mini), math.ult(0, 0))

-- large products
show("2^62 int", (1 << 62) * 2)
show("3037000500^2", 3037000500 * 3037000500)
show("1e308*10", 1e308 * 10)

-- results printed with tostring keep their subtype marker
print(tostring(10 // 1), tostring(10.0 // 1), tostring(10 / 1), tostring(-7 // 2.0))
print(1e15, 2^63, -2^63, 2^63 == mini, -2^63 == mini)
show("math.abs(-0.0)", math.abs(-0.0))
show("math.abs(-3)", math.abs(-3))
show("math.max(1, 2.0)", math.max(1, 2.0))
show("math.max(2, 1.0)", math.max(2, 1.0))
show("math.min(1, 1.0)", math.min(1, 1.0))
show("math.min(1.0, 1)", math.min(1.0, 1))
